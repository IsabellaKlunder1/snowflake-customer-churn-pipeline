
-- Customer Churn Pipeline
-- Data quality validation

CREATE OR REPLACE VIEW
CUSTOMER_CHURN_DB.ANALYTICS.DATA_QUALITY_STATUS AS
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMERID) AS UNIQUE_CUSTOMERS,

    COUNT_IF(CUSTOMERID IS NULL) AS MISSING_IDS,

    COUNT_IF(
        CHURN IS NULL
        OR UPPER(TRIM(CHURN)) NOT IN ('YES', 'NO')
    ) AS INVALID_CHURN,

    COUNT_IF(MONTHLYCHARGES < 0) AS NEGATIVE_CHARGES,

    COUNT_IF(TOTAL_CHARGES_CLEAN IS NULL)
        AS MISSING_TOTAL_CHARGES,

    CASE
        WHEN COUNT(*) = COUNT(DISTINCT CUSTOMERID)
         AND COUNT_IF(CUSTOMERID IS NULL) = 0
         AND COUNT_IF(
             CHURN IS NULL
             OR UPPER(TRIM(CHURN)) NOT IN ('YES', 'NO')
         ) = 0
         AND COUNT_IF(MONTHLYCHARGES < 0) = 0
        THEN 'PASS'
        ELSE 'FAIL'
    END AS TEST_STATUS

FROM CUSTOMER_CHURN_DB.STAGING.TELCO_CUSTOMERS;

-- View the validation results
SELECT *
FROM CUSTOMER_CHURN_DB.ANALYTICS.DATA_QUALITY_STATUS;
