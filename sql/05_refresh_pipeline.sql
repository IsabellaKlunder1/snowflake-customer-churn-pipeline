
-- Customer Churn Pipeline
-- Repeatable manual refresh

USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

-- Step 1: Refresh cleaned customer data
CREATE OR REPLACE TABLE CUSTOMER_CHURN_DB.STAGING.TELCO_CUSTOMERS AS
SELECT
    *,
    TRY_TO_DECIMAL(
        NULLIF(TRIM(TOTALCHARGES), ''),
        12, 2
    ) AS TOTAL_CHARGES_CLEAN
FROM CUSTOMER_CHURN_DB.RAW.TELCO_CUSTOMERS;

-- Step 2: Refresh churn analytics
CREATE OR REPLACE TABLE CUSTOMER_CHURN_DB.ANALYTICS.TELCO_CHURN_BY_CONTRACT AS
SELECT
    CONTRACT AS CONTRACT_TYPE,
    COUNT(*) AS TOTAL_CUSTOMERS,
    COUNT_IF(UPPER(TRIM(CHURN)) = 'YES')
        AS CHURNED_CUSTOMERS,
    ROUND(
        100.0 * COUNT_IF(UPPER(TRIM(CHURN)) = 'YES')
        / NULLIF(COUNT(*), 0),
        2
    ) AS CHURN_RATE_PERCENTAGE,
    ROUND(SUM(MONTHLYCHARGES), 2)
        AS MONTHLY_REVENUE,
    ROUND(
        SUM(
            CASE
                WHEN UPPER(TRIM(CHURN)) = 'YES'
                THEN MONTHLYCHARGES
                ELSE 0
            END
        ),
        2
    ) AS CHURNED_MONTHLY_REVENUE
FROM CUSTOMER_CHURN_DB.STAGING.TELCO_CUSTOMERS
GROUP BY CONTRACT;

-- Step 3: Verify row counts and quality status
SELECT
    (SELECT COUNT(*)
     FROM CUSTOMER_CHURN_DB.STAGING.TELCO_CUSTOMERS)
        AS STAGING_CUSTOMERS,

    (SELECT SUM(TOTAL_CUSTOMERS)
     FROM CUSTOMER_CHURN_DB.ANALYTICS.TELCO_CHURN_BY_CONTRACT)
        AS ANALYTICS_CUSTOMERS,

    (SELECT TEST_STATUS
     FROM CUSTOMER_CHURN_DB.ANALYTICS.DATA_QUALITY_STATUS)
        AS DATA_QUALITY_STATUS;
